"""Helpers for the storage performance steps, which drive storage-scale-test on Kubernetes.

storage-scale-test (https://github.com/NVIDIA/storage-scale-test) runs the benchmark. On
Kubernetes its launcher only submits: the sweep runs in-cluster, ``--status`` reports its
progress, and ``--collect`` copies the results back and releases what the sweep holds (the
claim's Lease, the coordinator Job and the worker DaemonSet). These helpers drive that
lifecycle synchronously, so one isvctl step can submit, wait and collect.
"""

from __future__ import annotations

import json
import os
import re
import shlex
import subprocess
import sys
import time
from pathlib import Path
from typing import Any

DEMO_MODE = os.environ.get("ISVCTL_DEMO_MODE") == "1"

LAUNCHER = Path("storage-tests") / "fs" / "nv-elbencho-sweep.sh"
VERSION_SCRIPT = Path("lib") / "project_version.sh"
EXTRACTOR = Path("utils") / "extract-elbencho.py"

# env.sh is read from the checkout root and has no path flag, so isvctl writes it there:
# env.sh.template with isvctl's settings inserted at the anchor storage-scale-test provides
# for integrations (just before the line that loads the defaults), as its own CI does.
ENV_TEMPLATE = "env.sh.template"
ENV_SH = "env.sh"
OVERRIDES_ANCHOR = "# STORAGE_SCALE_TEST_INTEGRATION_OVERRIDES"
GENERATED_MARKER = "# Generated by isvctl (storage performance steps); do not edit."

# `--status` keys (docs/KUBERNETES_ELBENCHO_LIFECYCLE.md in storage-scale-test).
NEXT_WAIT = "WAIT"
NEXT_COLLECT = "COLLECT"
COLLECTION_COMPLETE = "COMPLETE"
CANCEL_REQUESTED = "CANCEL_REQUESTED"
# Submit rolled back what it created (Jobs, workers, the claim's Lease); nothing to collect.
SUBMISSION_FAILED = "SUBMISSION_FAILED"
# Submit publishes this pointer before it changes anything in the cluster, so a results
# directory without it owns no cluster resource (and --status cannot inspect it).
CURRENT_ATTEMPT = Path("kubernetes") / "current-attempt"
# Every lifecycle command holds the results directory's lock (flock -n), and a concurrent
# one is refused with this message; storage-scale-test's answer is to wait and retry.
LOCK_BUSY = "another Kubernetes lifecycle operation is active"
LOCK_RETRY_INTERVAL_S = 5
LOCK_RETRIES = 6

_KV = re.compile(r"^([A-Za-z_][A-Za-z0-9_]*)=(.*)$")
# Keys the steps act on. Like storage-scale-test's own reader, accept them only when they
# appear exactly once; a repeated one is dropped, so the reply reads as unknown.
UNIQUE_KEYS = ("STORAGE_SCALE_TEST_RESULTS_DIR", "STORAGE_SCALE_TEST_ATTEMPT_ID", "STATE", "NEXT_ACTION")


class Budget:
    """A step's time limits for its storage-scale-test calls.

    Each call gets at most *command_timeout* seconds, and no call runs past the step's
    overall budget (*total_s*; 0 = no overall limit). Set the budget below the step's own
    timeout: a step that runs out of budget still reports what it did, while one that
    isvctl kills at its timeout reports nothing.
    """

    def __init__(self, command_timeout: int, total_s: int = 0) -> None:
        self.command_timeout = command_timeout
        self.deadline = time.monotonic() + total_s if total_s > 0 else None

    def remaining(self) -> float:
        """Seconds left in the step's budget."""
        return float("inf") if self.deadline is None else self.deadline - time.monotonic()

    def call_timeout(self) -> int:
        """The timeout for the next call: the command timeout, capped at the time left."""
        return max(1, int(min(self.command_timeout, self.remaining())))

    def spent(self) -> bool:
        """True once the step's budget is used up."""
        return self.remaining() <= 0


def log(message: str) -> None:
    """Write a progress line to stderr; stdout is reserved for the step's JSON."""
    print(message, file=sys.stderr, flush=True)


def emit(result: dict[str, Any]) -> int:
    """Print the step result as JSON and return the matching exit code."""
    print(json.dumps(result, indent=2))
    return 0 if result.get("success") else 1


def parse_kv(text: str) -> dict[str, str]:
    """Parse ``KEY=value`` lines; storage-scale-test prints its lifecycle state this way.

    It writes diagnostic values and FAILED_LOG with ``printf %q``, so those are unquoted.
    """
    out: dict[str, str] = {}
    seen: dict[str, int] = {}
    for line in text.splitlines():
        match = _KV.match(line.strip())
        if match:
            key, value = match.group(1), match.group(2)
            seen[key] = seen.get(key, 0) + 1
            if key.startswith("STORAGE_SCALE_TEST_DIAGNOSTIC_") or key == "FAILED_LOG":
                try:
                    value = " ".join(shlex.split(value))
                except ValueError:
                    pass
            out[key] = value
    for key in UNIQUE_KEYS:
        if seen.get(key, 0) > 1:
            log(f"ignoring {key}: storage-scale-test printed it {seen[key]} times")
            del out[key]
    return out


def run(cmd: list[str], timeout: int, env: dict[str, str] | None = None) -> subprocess.CompletedProcess[str]:
    """Run a command; a timeout comes back as exit code 124 instead of raising."""
    try:
        return subprocess.run(cmd, capture_output=True, text=True, timeout=timeout, env=env, check=False)
    except subprocess.TimeoutExpired as exc:
        stdout = exc.stdout.decode() if isinstance(exc.stdout, bytes) else (exc.stdout or "")
        return subprocess.CompletedProcess(cmd, 124, stdout, f"timed out after {timeout}s")


def describe_failure(stderr: str) -> str:
    """storage-scale-test's own explanation of a failed command.

    It prints ``Error: ...`` lines plus ``STORAGE_SCALE_TEST_DIAGNOSTIC_*`` fields to stderr;
    the last error and diagnostic say why the operation stopped, whether its workload may
    still be running, what to do next, and where it saved the evidence.
    """
    errors = [line[len("Error:") :].strip() for line in stderr.splitlines() if line.startswith("Error:")]
    fields = {k.removeprefix("STORAGE_SCALE_TEST_DIAGNOSTIC_"): v for k, v in parse_kv(stderr).items()}
    reason, phase = fields.get("REASON"), fields.get("PHASE")
    detail = f" ({reason}, phase {phase})" if reason and phase else (f" ({reason})" if reason else "")
    message = errors[-1] if errors else (stderr.strip().splitlines() or ["no error output"])[-1]
    extra = []
    if fields.get("MAY_STILL_BE_RUNNING") in ("yes", "unknown"):
        extra.append(f"may still be running: {fields['MAY_STILL_BE_RUNNING']}")
    if fields.get("SAFE_NEXT_ACTION"):
        extra.append(f"next: {fields['SAFE_NEXT_ACTION']}")
    if fields.get("PATH"):
        extra.append(f"diagnostics: {fields['PATH']}")
    return message + detail + "".join(f"; {item}" for item in extra)


def child_env(kubeconfig: str | None) -> dict[str, str]:
    """The environment for storage-scale-test: ours, pinned to the run's kubeconfig."""
    env = dict(os.environ)
    if kubeconfig:
        env["KUBECONFIG"] = kubeconfig
    return env


def launcher(base: Path) -> list[str]:
    """The IO sweep launcher. It needs bash 4.4+, which its shebang finds on PATH."""
    return [str(base / LAUNCHER)]


def tree_version(base: Path) -> str:
    """The tree's version as storage-scale-test resolves it.

    For a release source archive that checks every file against its SOURCE_SHA256, so an
    edited tree reads ``<version>-modified``; a Git checkout reads like ``v2.1.0-4-g<sha>``.
    """
    proc = run(["bash", str(base / VERSION_SCRIPT), "resolve", str(base)], 60)
    lines = proc.stdout.strip().splitlines()
    return lines[-1] if proc.returncode == 0 and lines else "unknown"


def has_attempt(results_dir: str) -> bool:
    """True once submit published an attempt; before that, it owns no cluster resource."""
    return (Path(results_dir) / CURRENT_ATTEMPT).is_file()


def lifecycle(
    base: Path, operation: str, results_dir: str, budget: Budget, env: dict[str, str]
) -> subprocess.CompletedProcess[str]:
    """Run ``--status``, ``--cancel`` or ``--collect``, retrying while another command holds the lock."""
    for attempt in range(LOCK_RETRIES + 1):
        proc = run([*launcher(base), operation, results_dir], budget.call_timeout(), env)
        if LOCK_BUSY not in proc.stderr or attempt == LOCK_RETRIES or budget.spent():
            return proc
        log(f"{operation}: another lifecycle command holds the lock; retrying")
        time.sleep(min(LOCK_RETRY_INTERVAL_S, max(0.0, budget.remaining())))
    return proc


def query(base: Path, results_dir: str, budget: Budget, env: dict[str, str]) -> tuple[int, dict[str, str]]:
    """Ask storage-scale-test for the sweep's state.

    Returns the exit code and the parsed keys. A failed query (lost API access, an expired
    credential) is not evidence that the sweep failed: it keeps running in-cluster, so
    callers treat it as "unknown" and ask again.
    """
    proc = lifecycle(base, "--status", results_dir, budget, env)
    fields = parse_kv(proc.stdout)
    reason = parse_kv(proc.stderr).get("STORAGE_SCALE_TEST_DIAGNOSTIC_REASON")
    if reason:
        fields["DIAGNOSTIC_REASON"] = reason
    if proc.returncode != 0 and fields.get("STATE") == CANCEL_REQUESTED and fields.get("NEXT_ACTION"):
        # An incomplete cancel is a known state, which --status reports with exit 1.
        return 0, fields
    if proc.returncode != 0:
        log(f"--status exited {proc.returncode}: {proc.stderr.strip()[-500:]}")
    return proc.returncode, fields


def wait_for_terminal(
    base: Path, results_dir: str, deadline_s: float, interval_s: int, budget: Budget, env: dict[str, str]
) -> tuple[bool, dict[str, str]]:
    """Poll ``--status`` until the sweep needs no more waiting, or the deadline passes.

    Returns ``(finished, last_known_status)``. Any NEXT_ACTION other than WAIT ends the wait:
    COLLECT for a finished run, INSPECT for a failed submission or a pending cancel.
    """
    deadline = time.monotonic() + deadline_s
    last: dict[str, str] = {}
    while True:
        rc, fields = query(base, results_dir, budget, env)
        if rc == 0 and fields.get("NEXT_ACTION"):
            last = fields
            log(
                f"sweep {fields.get('STATE')}: {fields.get('EXECUTIONS_SUCCEEDED', '?')}"
                f"/{fields.get('EXECUTIONS_TOTAL', '?')} done, next {fields['NEXT_ACTION']}"
            )
            if fields["NEXT_ACTION"] != NEXT_WAIT:
                return True, last
        else:
            log(f"sweep state unknown ({fields.get('DIAGNOSTIC_REASON', 'no status')}); it keeps running in-cluster")
        if time.monotonic() + interval_s > deadline:
            return False, last
        time.sleep(interval_s)


def collect(base: Path, results_dir: str, budget: Budget, env: dict[str, str], attempts: int = 3) -> dict[str, Any]:
    """Run ``--collect`` until the sweep's cluster resources are released.

    ``--collect`` exits nonzero for a FAILED or CANCELLED attempt even after publishing the
    cells that finished, so its exit code alone does not say whether collection worked;
    ``RESULT_COLLECTION=COMPLETE`` does. A collect can publish the results yet leave cleanup
    pending (``NEXT_ACTION=COLLECT``); storage-scale-test's answer is to collect again.
    """
    out: dict[str, Any] = {"resources_released": False}
    for attempt in range(1, attempts + 1):
        if budget.spent():
            out["collect_error"] = "the step's time budget ran out before collect finished"
            break
        proc = lifecycle(base, "--collect", results_dir, budget, env)
        out["collect_exit_code"] = proc.returncode
        failed = parse_kv(proc.stdout)
        for key in ("FAILED_EXECUTION", "FAILED_LOG"):
            if failed.get(key):
                out[key.lower()] = failed[key]
        rc, status = query(base, results_dir, budget, env)
        if rc != 0:
            out["collect_error"] = "could not confirm the sweep's resources were released"
            continue
        out["result_collection"] = status.get("RESULT_COLLECTION")
        if status.get("RESULT_COLLECTION") == COLLECTION_COMPLETE:
            out["resources_released"] = True
            out.pop("collect_error", None)
            return out
        if status.get("NEXT_ACTION") != NEXT_COLLECT:
            break
        log(f"collect {attempt}: cleanup still pending (RESULT_COLLECTION={status.get('RESULT_COLLECTION')})")
    reason = out.get("collect_error") or f"RESULT_COLLECTION={out.get('result_collection')}"
    out["collect_error"] = (
        f"the sweep still holds cluster resources ({reason}); "
        f"run `{base / LAUNCHER} --collect {results_dir}` to release them"
    )
    return out


def cancel(base: Path, results_dir: str, budget: Budget, env: dict[str, str], attempts: int = 3) -> bool:
    """Stop a running sweep; True once storage-scale-test reports it can be collected.

    Cancel is two-phase: it can leave the attempt in CANCEL_REQUESTED, and the documented
    response is to cancel again. Cancelling does not release anything; collect does.
    """
    for _ in range(attempts):
        if budget.spent():
            return False
        lifecycle(base, "--cancel", results_dir, budget, env)
        rc, status = query(base, results_dir, budget, env)
        if rc == 0 and status.get("STATE") != CANCEL_REQUESTED and status.get("NEXT_ACTION") != NEXT_WAIT:
            return True
    return False


def compose_env_sh(template: str, settings: list[str]) -> str:
    """Insert isvctl's settings into env.sh.template at its integration-overrides anchor."""
    lines = template.splitlines(keepends=True)
    anchors = [index for index, line in enumerate(lines) if line.strip() == OVERRIDES_ANCHOR]
    if len(anchors) != 1:
        raise ValueError(
            f"{ENV_TEMPLATE} has {len(anchors)} {OVERRIDES_ANCHOR!r} lines, not one; "
            "this storage-scale-test version is not supported"
        )
    block = [GENERATED_MARKER + "\n", *(s + "\n" for s in settings), "\n"]
    return "".join(lines[: anchors[0]] + block + lines[anchors[0] :])


def install_env_sh(base: Path, settings: list[str]) -> Path:
    """Write the checkout's env.sh, refusing to replace one isvctl did not write."""
    path = base / ENV_SH
    if path.is_symlink() or (
        path.exists() and GENERATED_MARKER not in path.read_text(encoding="utf-8", errors="replace")
    ):
        raise FileExistsError(
            f"{path} exists and was not written by isvctl. Point --scale-test-base at a checkout "
            "used only by isvctl, or move that env.sh aside."
        )
    text = compose_env_sh((base / ENV_TEMPLATE).read_text(encoding="utf-8"), settings)
    tmp = path.with_name(ENV_SH + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    tmp.replace(path)
    return path


def bash_quote(value: str) -> str:
    """Single-quote a value for Bash."""
    return "'" + value.replace("'", "'\\''") + "'"


def bash_array(values: list[str]) -> str:
    """A Bash indexed-array literal."""
    return "(" + " ".join(bash_quote(v) for v in values) + ")"


def read_state(path: str) -> dict[str, Any] | None:
    """Read the run's state file, or None when there is none."""
    try:
        return json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


def write_state(path: str, state: dict[str, Any]) -> None:
    """Atomically write the run's state file, the handle teardown uses to clean up."""
    target = Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    tmp = target.with_name(target.name + ".tmp")
    tmp.write_text(json.dumps(state, indent=2), encoding="utf-8")
    tmp.replace(target)
